# 1. Crear los conjuntos
A = {1, 2, 3, 4, 5}
B = {4, 5, 6, 7, 8}
print("Conjunto A:", A)
print("Conjunto B:", B)

# 2. Unión de los conjuntos
union = A | B
print("Unión de A y B:", union)

# 3. Intersección de los conjuntos
interseccion = A & B
print("Intersección de A y B:", interseccion)

# 4. Diferencia (A - B) entre conjuntos 
diferencia = A - B
print("Diferencia A - B:", diferencia)